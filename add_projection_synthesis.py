                                          'def fit_projection(\n'
                                          '    motion: FourBarMotion,\n'
                                          '    target_q: np.ndarray | tuple[float, ...],\n'
                                          '    *,\n'
                                          '    output_type: OutputType,\n'
                                          '    target_dq_dtheta: np.ndarray | tuple[float, ...] | '
                                          'None = None,\n'
                                          '    derivative_weight: float = 0.0,\n'
                                          '    phase_rad: float = 0.0,\n'
                                          ') -> ProjectionFit:\n'
                                          '    """Solve analytically for the best output '
                                          'point/projection coefficients."""\n'
                                          '\n'
                                          '    q = np.asarray(target_q, dtype=float)\n'
                                          '    if q.ndim != 1 or not np.all(np.isfinite(q)):\n'
                                          '        raise ValueError("target_q must be a '
                                          'one-dimensional finite array.")\n'
                                          '    position_basis, derivative_basis = '
                                          'projection_basis(motion, output_type)\n'
                                          '    if len(q) != position_basis.shape[0]:\n'
                                          '        raise ValueError("target_q sample count does '
                                          'not match the four-bar motion.")\n'
                                          '    if not math.isfinite(derivative_weight) or '
                                          'derivative_weight < 0.0:\n'
                                          '        raise ValueError("derivative_weight must be '
                                          'finite and non-negative.")\n'
                                          '\n'
                                          '    dq = None\n'
                                          '    if target_dq_dtheta is not None:\n'
                                          '        dq = np.asarray(target_dq_dtheta, dtype=float)\n'
                                          '        if dq.shape != q.shape or not '
                                          'np.all(np.isfinite(dq)):\n'
                                          '            raise ValueError("target_dq_dtheta must '
                                          'match target_q with finite values.")\n'
                                          '    if derivative_weight > 0.0 and dq is None:\n'
                                          '        raise ValueError("A derivative target is '
                                          'required when derivative_weight is positive.")\n'
                                          '\n'
                                          '    if derivative_weight > 0.0:\n'
                                          '        root_weight = math.sqrt(derivative_weight)\n'
                                          '        matrix = np.vstack((position_basis, root_weight '
                                          '* derivative_basis))\n'
                                          '        rhs = np.concatenate((q, root_weight * dq))\n'
                                          '    else:\n'
                                          '        matrix = position_basis\n'
                                          '        rhs = q\n'
                                          '\n'
                                          '    coefficients, *_ = np.linalg.lstsq(matrix, rhs, '
                                          'rcond=None)\n'
                                          '    predicted = position_basis @ coefficients\n'
                                          '    position_error = predicted - q\n'
                                          '    position_rms = float(np.sqrt(np.mean(position_error '
                                          '* position_error)))\n'
                                          '    maximum_error = '
                                          'float(np.max(np.abs(position_error)))\n'
                                          '\n'
                                          '    derivative_rms = None\n'
                                          '    derivative_term = 0.0\n'
                                          '    if dq is not None:\n'
                                          '        derivative_error = derivative_basis @ '
                                          'coefficients - dq\n'
                                          '        derivative_rms = '
                                          'float(np.sqrt(np.mean(derivative_error * '
                                          'derivative_error)))\n'
                                          '        derivative_term = derivative_weight * '
                                          'derivative_rms * derivative_rms\n'
                                          '    objective_rms = math.sqrt(position_rms * '
                                          'position_rms + derivative_term)\n'
                                          '\n'
                                          '    return ProjectionFit(\n'
                                          '        output_type=output_type,\n'
                                          '        coefficients=tuple(float(value) for value in '
                                          'coefficients),\n'
                                          '        position_rms=position_rms,\n'
                                          '        derivative_rms=derivative_rms,\n'
                                          '        maximum_absolute_position_error=maximum_error,\n'
                                          '        objective_rms=objective_rms,\n'
                                          '        recovery=_recover_projection(coefficients, '
                                          'output_type, phase_rad),\n'
                                          '    )\n'
                                          '\n'
                                          '\n'
                                          'def search_projection(\n'
                                          '    theta_rad: np.ndarray | tuple[float, ...],\n'
                                          '    target_q: np.ndarray | tuple[float, ...],\n'
                                          '    *,\n'
                                          '    output_type: OutputType,\n'
                                          '    assembly_branch: int,\n'
                                          '    target_dq_dtheta: np.ndarray | tuple[float, ...] | '
                                          'None = None,\n'
                                          '    derivative_weight: float = 0.0,\n'
                                          '    ratio_minimum: float = 0.2,\n'
                                          '    ratio_maximum: float = 6.0,\n'
                                          '    maximum_iterations: int = 80,\n'
                                          '    population_size: int = 10,\n'
                                          '    seed: int = 27,\n'
                                          ') -> ProjectionSearchResult:\n'
                                          '    """Search three link ratios and phase; solve output '
                                          'coordinates analytically."""\n'
                                          '\n'
                                          '    if assembly_branch not in (-1, 1):\n'
                                          '        raise ValueError("assembly_branch must be -1 or '
                                          '1.")\n'
                                          '    for name, value in (("ratio_minimum", '
                                          'ratio_minimum), ("ratio_maximum", ratio_maximum)):\n'
                                          '        if not math.isfinite(value) or value <= 0.0:\n'
                                          '            raise ValueError(f"{name} must be finite '
                                          'and positive.")\n'
                                          '    if ratio_maximum <= ratio_minimum:\n'
                                          '        raise ValueError("ratio_maximum must exceed '
                                          'ratio_minimum.")\n'
                                          '    if maximum_iterations <= 0 or population_size < 4:\n'
                                          '        raise ValueError("Search iteration and '
                                          'population limits are too small.")\n'
                                          '\n'
                                          '    theta = np.asarray(theta_rad, dtype=float)\n'
                                          '    q = np.asarray(target_q, dtype=float)\n'
                                          '    dq = None if target_dq_dtheta is None else '
                                          'np.asarray(target_dq_dtheta, dtype=float)\n'
                                          '    invalid_penalty = 1.0e6\n'
                                          '\n'
                                          '    def objective(vector: np.ndarray) -> float:\n'
                                          '        geometry = NormalizedFourBarGeometry(\n'
                                          '            ground_ratio=math.exp(float(vector[0])),\n'
                                          '            coupler_ratio=math.exp(float(vector[1])),\n'
                                          '            rocker_ratio=math.exp(float(vector[2])),\n'
                                          '            phase_rad=float(vector[3]),\n'
                                          '            assembly_branch=assembly_branch,\n'
                                          '        )\n'
                                          '        try:\n'
                                          '            motion = evaluate_four_bar(theta, '
                                          'geometry)\n'
                                          '            fit = fit_projection(\n'
                                          '                motion,\n'
                                          '                q,\n'
                                          '                output_type=output_type,\n'
                                          '                target_dq_dtheta=dq,\n'
                                          '                derivative_weight=derivative_weight,\n'
                                          '                phase_rad=geometry.phase_rad,\n'
                                          '            )\n'
                                          '        except (ValueError, FloatingPointError, '
                                          'np.linalg.LinAlgError):\n'
                                          '            return invalid_penalty\n'
                                          '        return fit.objective_rms\n'
                                          '\n'
                                          '    logarithmic_bounds = (math.log(ratio_minimum), '
                                          'math.log(ratio_maximum))\n'
                                          '    result = differential_evolution(\n'
                                          '        objective,\n'
                                          '        bounds=(\n'
                                          '            logarithmic_bounds,\n'
                                          '            logarithmic_bounds,\n'
                                          '            logarithmic_bounds,\n'
                                          '            (-math.pi, math.pi),\n'
                                          '        ),\n'
                                          '        maxiter=maximum_iterations,\n'
                                          '        popsize=population_size,\n'
                                          '        seed=seed,\n'
