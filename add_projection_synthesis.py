                                          '\n'
                                          '    g = geometry.ground_ratio\n'
                                          '    c = geometry.coupler_ratio\n'
                                          '    r = geometry.rocker_ratio\n'
                                          '    scale = max(1.0, g, c, r)\n'
                                          '    tolerance = singularity_tolerance * scale\n'
                                          '\n'
                                          '    minimum_center_distance = abs(g - 1.0)\n'
                                          '    maximum_center_distance = g + 1.0\n'
                                          '    outer_margin = c + r - maximum_center_distance\n'
                                          '    inner_margin = minimum_center_distance - abs(c - '
                                          'r)\n'
                                          '    if minimum_center_distance <= tolerance:\n'
                                          '        raise ValueError("Four-bar circle centers '
                                          'coincide or nearly coincide during the cycle.")\n'
                                          '    if outer_margin <= tolerance:\n'
                                          '        raise ValueError("Four-bar cannot complete a '
                                          'crank revolution: outer closure limit.")\n'
                                          '    if inner_margin <= tolerance:\n'
                                          '        raise ValueError("Four-bar cannot complete a '
                                          'crank revolution: inner closure limit.")\n'
                                          '\n'
                                          '    crank_angle = theta + geometry.phase_rad\n'
                                          '    crank = np.column_stack((np.cos(crank_angle), '
                                          'np.sin(crank_angle)))\n'
                                          '    crank_derivative = '
                                          'np.column_stack((-np.sin(crank_angle), '
                                          'np.cos(crank_angle)))\n'
                                          '    pivot = np.array((g, 0.0), dtype=float)\n'
                                          '\n'
                                          '    delta = pivot - crank\n'
                                          '    distance = np.linalg.norm(delta, axis=1)\n'
                                          '    direction = delta / distance[:, None]\n'
                                          '    along = (c * c - r * r + distance * distance) / '
                                          '(2.0 * distance)\n'
                                          '    height_squared = c * c - along * along\n'
                                          '    if np.any(height_squared <= tolerance * '
