                                          'def _recover_projection(\n'
                                          '    coefficients: np.ndarray,\n'
                                          '    output_type: OutputType,\n'
                                          '    phase_rad: float,\n'
                                          ') -> ProjectionRecovery | None:\n'
                                          '    if output_type == "rocker":\n'
                                          '        x, y = float(coefficients[1]), '
                                          'float(coefficients[2])\n'
                                          '        scale = math.hypot(x, y)\n'
                                          '        if scale <= 64.0 * np.finfo(float).eps:\n'
                                          '            return None\n'
                                          '        axis = math.atan2(y, x)\n'
                                          '        # Gauge choice: place E one crank radius along '
                                          'the rocker. Any radial\n'
                                          '        # scaling is equivalent in projection-only '
                                          'synthesis and is absorbed by\n'
                                          '        # normalized_projection_scale.\n'
                                          '        return ProjectionRecovery(\n'
                                          '            axis_angle_canonical_rad=axis,\n'
                                          '            axis_angle_shared_crank_rad=axis - '
                                          'phase_rad,\n'
                                          '            output_along_ratio=1.0,\n'
                                          '            output_normal_ratio=0.0,\n'
                                          '            normalized_projection_scale=scale,\n'
                                          '        )\n'
                                          '\n'
                                          '    crank_x, crank_y = float(coefficients[1]), '
                                          'float(coefficients[2])\n'
                                          '    scale = math.hypot(crank_x, crank_y)\n'
                                          '    if scale <= 64.0 * np.finfo(float).eps:\n'
                                          '        return None\n'
                                          '    axis = math.atan2(crank_y, crank_x)\n'
                                          '    coupler_x, coupler_y = float(coefficients[3]), '
                                          'float(coefficients[4])\n'
                                          '    along = (coupler_x * math.cos(axis) + coupler_y * '
                                          'math.sin(axis)) / scale\n'
                                          '    normal = (coupler_x * math.sin(axis) - coupler_y * '
                                          'math.cos(axis)) / scale\n'
                                          '    return ProjectionRecovery(\n'
                                          '        axis_angle_canonical_rad=axis,\n'
                                          '        axis_angle_shared_crank_rad=axis - phase_rad,\n'
                                          '        output_along_ratio=along,\n'
                                          '        output_normal_ratio=normal,\n'
                                          '        normalized_projection_scale=scale,\n'
                                          '    )\n'
