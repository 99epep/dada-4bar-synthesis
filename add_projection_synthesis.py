                                          '        raise ValueError("Four-bar reaches a toggle '
                                          'singularity.")\n'
                                          '    height = np.sqrt(height_squared)\n'
                                          '    left_normal = np.column_stack((-direction[:, 1], '
                                          'direction[:, 0]))\n'
                                          '    joint = (\n'
                                          '        crank\n'
                                          '        + along[:, None] * direction\n'
                                          '        + geometry.assembly_branch * height[:, None] * '
                                          'left_normal\n'
                                          '    )\n'
                                          '\n'
                                          '    coupler_vector = joint - crank\n'
                                          '    rocker_vector = joint - pivot\n'
                                          '    determinant = (\n'
                                          '        coupler_vector[:, 0] * rocker_vector[:, 1]\n'
                                          '        - coupler_vector[:, 1] * rocker_vector[:, 0]\n'
                                          '    )\n'
                                          '    if np.any(np.abs(determinant) <= '
