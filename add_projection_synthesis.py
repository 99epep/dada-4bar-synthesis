                                          '                motion.rocker_unit_derivative[:, 1],\n'
                                          '            )\n'
                                          '        )\n'
                                          '    elif output_type == "coupler":\n'
                                          '        position = np.column_stack(\n'
                                          '            (\n'
                                          '                ones,\n'
                                          '                motion.crank_xy[:, 0],\n'
                                          '                motion.crank_xy[:, 1],\n'
                                          '                motion.coupler_unit[:, 0],\n'
                                          '                motion.coupler_unit[:, 1],\n'
                                          '            )\n'
                                          '        )\n'
                                          '        derivative = np.column_stack(\n'
                                          '            (\n'
                                          '                zeros,\n'
                                          '                motion.crank_dxy_dtheta[:, 0],\n'
                                          '                motion.crank_dxy_dtheta[:, 1],\n'
                                          '                motion.coupler_unit_derivative[:, 0],\n'
                                          '                motion.coupler_unit_derivative[:, 1],\n'
                                          '            )\n'
                                          '        )\n'
                                          '    else:\n'
                                          '        raise ValueError("output_type must be '
                                          '\'rocker\' or \'coupler\'.")\n'
                                          '    return position, derivative\n'
